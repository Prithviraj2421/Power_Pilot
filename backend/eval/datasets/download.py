"""Download the benchmark datasets listed in manifest.json and pin them in manifest.lock.json.

    python -m eval.datasets.download            # fetch what is missing, verify checksums of what exists

Public datasets come from the UCI Machine Learning Repository (`data.csv` endpoint). The licence text is read
from each dataset's own page at download time, never typed by hand. Files larger than `max_rows` are sampled with
the manifest's fixed seed, so every machine gets the same rows; the lock records that.
Local entries (the repo's own synthetic samples) are copied as they are.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import re
import shutil
import sys
import urllib.request
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
BACKEND = HERE.parents[1]
RAW = HERE / "raw"
MANIFEST = HERE / "manifest.json"
LOCK = HERE / "manifest.lock.json"
PAGE = "https://archive.ics.uci.edu/dataset/{uci_id}"
DATA = "https://archive.ics.uci.edu/static/public/{uci_id}/data.csv"
_LICENSE = re.compile(r"(This dataset is licensed under[^<]{0,200}?\.)", re.IGNORECASE)


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "powerpilot-eval/1.0"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read()


def licence_of(uci_id: int) -> tuple[str, str]:
    page = PAGE.format(uci_id=uci_id)
    html = fetch(page).decode("utf-8", errors="replace")
    text = re.sub(r"<[^>]+>", " ", html)
    match = _LICENSE.search(re.sub(r"\s+", " ", text))
    return page, (match.group(1) if match else "NOT FOUND ON PAGE: check the dataset page by hand")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    lock = json.loads(LOCK.read_text(encoding="utf-8")) if LOCK.exists() else {}
    RAW.mkdir(exist_ok=True)
    failures = 0
    for entry in manifest["datasets"]:
        ident, target = entry["id"], RAW / f"{entry['id']}.csv"
        record = lock.get(ident, {})
        try:
            if "local" in entry:
                source = BACKEND / entry["local"]
                shutil.copyfile(source, target)
                record.update(source=f"repository file {entry['local']}", licence="Synthetic or generated by this project; same licence as the repository.")
            elif not target.exists():
                frame = pd.read_csv(DATA.format(uci_id=entry["uci_id"]), low_memory=False)
                total = len(frame)
                if total > manifest["max_rows"]:
                    frame = frame.sample(n=manifest["max_rows"], random_state=manifest["seed"]).sort_index()
                frame.to_csv(target, index=False)
                page, licence = licence_of(entry["uci_id"])
                record.update(source=page, data_url=DATA.format(uci_id=entry["uci_id"]), licence=licence, rows_in_source=total)
            frame = pd.read_csv(target, low_memory=False)
            record.update(
                title=entry["title"], domain=entry["domain"], rows=len(frame), columns=len(frame.columns), sha256=sha256(target),
                retrieved=record.get("retrieved", dt.date.today().isoformat()),
            )
            if "rows_in_source" in record and record["rows_in_source"] > len(frame):
                record["sampled"] = f"{len(frame)} rows, seed {manifest['seed']}"
            if record.get("sha256_expected") and record["sha256_expected"] != record["sha256"]:
                print(f"CHECKSUM CHANGED: {ident}", file=sys.stderr)
                failures += 1
            record.setdefault("sha256_expected", record["sha256"])
            lock[ident] = record
            print(f"ok  {ident:28} {record['rows']:>6} x {record['columns']:<3} {record['licence'][:70]}")
        except Exception as exc:  # one broken download must not hide the others
            print(f"ERR {ident}: {exc}", file=sys.stderr)
            failures += 1
    LOCK.write_text(json.dumps(lock, indent=2, ensure_ascii=False), encoding="utf-8")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
